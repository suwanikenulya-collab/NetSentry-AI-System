import {
  useState,
  type ChangeEvent,
} from "react";
import {
  Activity,
  ChartNoAxesCombined,
  CircleAlert,
  Clock3,
  Database,
  LoaderCircle,
  Search,
  Upload,
} from "lucide-react";

import { analyzeTrafficFile } from "../service/trafficApi";
import type {
  TrafficSummaryResponse,
} from "../types/traffic.types";


const TABLE_COLUMNS = [
  "Timestamp",
  "Source IP",
  "Destination IP",
  "Source port",
  "Destination port",
  "Protocol",
  "Packets",
  "Bytes",
  "Duration",
];


function formatTimestamp(timestamp: string) {
  const date = new Date(timestamp);

  if (Number.isNaN(date.getTime())) {
    return timestamp;
  }

  return date.toLocaleString();
}


export function TrafficAnalysisPage() {
  const [selectedFile, setSelectedFile] =
    useState<File | null>(null);

  const [analysisResult, setAnalysisResult] =
    useState<TrafficSummaryResponse | null>(null);

  const [isAnalyzing, setIsAnalyzing] =
    useState(false);

  const [errorMessage, setErrorMessage] =
    useState<string | null>(null);

  const [searchTerm, setSearchTerm] =
    useState("");


  function handleFileChange(
    event: ChangeEvent<HTMLInputElement>,
  ) {
    const file =
      event.target.files?.[0] ?? null;

    setSelectedFile(file);
    setAnalysisResult(null);
    setErrorMessage(null);
    setSearchTerm("");
  }


  async function handleAnalyze() {
    if (!selectedFile) {
      setErrorMessage(
        "Please choose a CSV file before starting the analysis.",
      );

      return;
    }

    setIsAnalyzing(true);
    setErrorMessage(null);
    setAnalysisResult(null);
    setSearchTerm("");

    try {
      const result =
        await analyzeTrafficFile(selectedFile);

      setAnalysisResult(result);
    } catch (error) {
      const message =
        error instanceof Error
          ? error.message
          : "The traffic dataset could not be analyzed.";

      setErrorMessage(message);
    } finally {
      setIsAnalyzing(false);
    }
  }


  const records =
    analysisResult?.records ?? [];

  const normalizedSearchTerm =
    searchTerm.trim().toLowerCase();

  const filteredRecords = records.filter(
    (record) => {
      if (!normalizedSearchTerm) {
        return true;
      }

      const searchableValues = [
        record.timestamp,
        record.src_ip,
        record.dst_ip,
        record.src_port,
        record.dst_port,
        record.protocol,
        record.pkt_count,
        record.bytes,
        record.duration,
      ];

      return searchableValues.some((value) =>
        String(value)
          .toLowerCase()
          .includes(normalizedSearchTerm),
      );
    },
  );


  const summaryCards = [
    {
      label: "Total connections",
      value: analysisResult
        ? analysisResult.total_connections.toLocaleString()
        : "--",
      description: analysisResult
        ? "Traffic records analyzed"
        : "No dataset analyzed",
      icon: Database,
      iconStyle: "bg-primary/10 text-primary",
    },
    {
      label: "Total packets",
      value: analysisResult
        ? analysisResult.total_packets.toLocaleString()
        : "--",
      description: analysisResult
        ? "Packets in the dataset"
        : "Awaiting analysis",
      icon: Activity,
      iconStyle: "bg-low/10 text-low",
    },
    {
      label: "Total bytes",
      value: analysisResult
        ? analysisResult.total_bytes.toLocaleString()
        : "--",
      description: analysisResult
        ? "Bytes transferred"
        : "Awaiting analysis",
      icon: ChartNoAxesCombined,
      iconStyle: "bg-medium/10 text-medium",
    },
    {
      label: "Average duration",
      value: analysisResult
        ? `${analysisResult.average_duration_seconds.toFixed(2)}s`
        : "--",
      description: analysisResult
        ? "Average connection duration"
        : "Awaiting analysis",
      icon: Clock3,
      iconStyle: "bg-critical/10 text-critical",
    },
  ];


  return (
    <main className="space-y-6">
      <header>
        <p className="text-sm font-medium text-primary">
          Network monitoring
        </p>

        <h1 className="mt-1 text-3xl font-bold text-foreground">
          Traffic Analysis
        </h1>

        <p className="mt-2 max-w-3xl text-muted">
          Upload a network-flow dataset and inspect the traffic
          statistics generated by the NetSentry backend.
        </p>
      </header>


      <section className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        {summaryCards.map(
          ({
            label,
            value,
            description,
            icon: Icon,
            iconStyle,
          }) => (
            <article
              key={label}
              className="rounded-2xl border border-border bg-surface p-5"
            >
              <div className="flex items-start justify-between gap-4">
                <div>
                  <p className="text-sm text-muted">
                    {label}
                  </p>

                  <p className="mt-3 text-3xl font-bold text-foreground">
                    {value}
                  </p>

                  <p className="mt-2 text-xs text-subtle">
                    {description}
                  </p>
                </div>

                <div
                  className={`flex h-10 w-10 shrink-0 items-center justify-center rounded-xl ${iconStyle}`}
                >
                  <Icon
                    className="h-5 w-5"
                    aria-hidden="true"
                  />
                </div>
              </div>
            </article>
          ),
        )}
      </section>


      <section className="rounded-2xl border border-primary/30 bg-primary/5 p-6">
        <div className="flex flex-col gap-5">
          <div className="flex flex-col gap-5 sm:flex-row sm:items-center sm:justify-between">
            <div className="flex items-start gap-4">
              <div className="flex h-11 w-11 shrink-0 items-center justify-center rounded-xl bg-primary/10 text-primary">
                <ChartNoAxesCombined
                  className="h-6 w-6"
                  aria-hidden="true"
                />
              </div>

              <div>
                <h2 className="font-semibold text-foreground">
                  {analysisResult
                    ? "Analysis completed"
                    : selectedFile
                      ? "Dataset selected"
                      : "No analysis results yet"}
                </h2>

                <p className="mt-1 max-w-2xl text-sm leading-6 text-muted">
                  {analysisResult
                    ? (
                      `${analysisResult.filename} was successfully `
                      + "analyzed by the FastAPI backend."
                    )
                    : selectedFile
                      ? (
                        `${selectedFile.name} is ready to be `
                        + "sent to the analysis service."
                      )
                      : (
                        "Choose a network-traffic CSV file to "
                        + "generate a real analysis."
                      )}
                </p>

                {selectedFile && (
                  <div className="mt-3 flex flex-wrap gap-3 text-xs text-subtle">
                    <span>
                      File: {selectedFile.name}
                    </span>

                    <span>
                      Size:{" "}
                      {(
                        selectedFile.size / 1024
                      ).toFixed(2)}{" "}
                      KB
                    </span>
                  </div>
                )}
              </div>
            </div>

            <div className="flex flex-col gap-3 sm:flex-row">
              <label className="inline-flex shrink-0 cursor-pointer items-center justify-center gap-2 rounded-lg border border-border-strong bg-surface px-4 py-2.5 text-sm font-medium text-foreground transition hover:bg-surface-hover">
                <Upload
                  className="h-4 w-4"
                  aria-hidden="true"
                />

                {selectedFile
                  ? "Change CSV"
                  : "Choose CSV"}

                <input
                  type="file"
                  accept=".csv,text/csv"
                  onChange={handleFileChange}
                  className="sr-only"
                />
              </label>

              <button
                type="button"
                onClick={() => void handleAnalyze()}
                disabled={!selectedFile || isAnalyzing}
                className="inline-flex shrink-0 items-center justify-center gap-2 rounded-lg bg-primary px-4 py-2.5 text-sm font-medium text-primary-foreground transition hover:opacity-90 disabled:cursor-not-allowed disabled:opacity-50"
              >
                {isAnalyzing ? (
                  <>
                    <LoaderCircle
                      className="h-4 w-4 animate-spin"
                      aria-hidden="true"
                    />

                    Analyzing...
                  </>
                ) : (
                  <>
                    <ChartNoAxesCombined
                      className="h-4 w-4"
                      aria-hidden="true"
                    />

                    Analyze dataset
                  </>
                )}
              </button>
            </div>
          </div>

          {errorMessage && (
            <div
              role="alert"
              className="flex items-start gap-3 rounded-xl border border-critical/30 bg-critical/10 p-4 text-sm text-critical"
            >
              <CircleAlert
                className="mt-0.5 h-5 w-5 shrink-0"
                aria-hidden="true"
              />

              <p>{errorMessage}</p>
            </div>
          )}

          {analysisResult && (
            <div className="rounded-xl border border-low/30 bg-low/10 p-4 text-sm text-low">
              The backend successfully analyzed{" "}
              {analysisResult.total_connections.toLocaleString()}{" "}
              network connections.
            </div>
          )}
        </div>
      </section>


      <section className="grid gap-6 xl:grid-cols-2">
        <article className="rounded-2xl border border-border bg-surface p-6">
          <h2 className="text-lg font-semibold text-foreground">
            Top source IP addresses
          </h2>

          <p className="mt-1 text-sm text-muted">
            Devices that created the most network connections.
          </p>

          {analysisResult
          && analysisResult.top_source_ips.length > 0 ? (
            <div className="mt-6 space-y-3">
              {analysisResult.top_source_ips.map(
                (source, index) => (
                  <div
                    key={source.ip_address}
                    className="flex items-center justify-between rounded-xl border border-border bg-background p-4"
                  >
                    <div className="flex items-center gap-3">
                      <span className="flex h-8 w-8 items-center justify-center rounded-lg bg-primary/10 text-sm font-semibold text-primary">
                        {index + 1}
                      </span>

                      <span className="font-mono text-sm text-foreground">
                        {source.ip_address}
                      </span>
                    </div>

                    <span className="text-sm font-semibold text-foreground">
                      {source.connections} connections
                    </span>
                  </div>
                ),
              )}
            </div>
          ) : (
            <div className="mt-6 flex min-h-52 flex-col items-center justify-center rounded-xl border border-dashed border-border-strong bg-background p-8 text-center">
              <Database className="h-10 w-10 text-subtle" />

              <p className="mt-4 text-sm text-muted">
                Analyze a dataset to view source IP activity.
              </p>
            </div>
          )}
        </article>


        <article className="rounded-2xl border border-border bg-surface p-6">
          <h2 className="text-lg font-semibold text-foreground">
            Protocol distribution
          </h2>

          <p className="mt-1 text-sm text-muted">
            Number of connections using each network protocol.
          </p>

          {analysisResult
          && analysisResult.protocol_counts.length > 0 ? (
            <div className="mt-6 space-y-3">
              {analysisResult.protocol_counts.map(
                (protocol) => (
                  <div
                    key={protocol.protocol}
                    className="flex items-center justify-between rounded-xl border border-border bg-background p-4"
                  >
                    <span className="font-semibold text-primary">
                      {protocol.protocol}
                    </span>

                    <span className="text-sm text-foreground">
                      {protocol.connections} connections
                    </span>
                  </div>
                ),
              )}
            </div>
          ) : (
            <div className="mt-6 flex min-h-52 flex-col items-center justify-center rounded-xl border border-dashed border-border-strong bg-background p-8 text-center">
              <Activity className="h-10 w-10 text-subtle" />

              <p className="mt-4 text-sm text-muted">
                Analyze a dataset to view protocol statistics.
              </p>
            </div>
          )}
        </article>
      </section>


      <section className="overflow-hidden rounded-2xl border border-border bg-surface">
        <div className="flex flex-col gap-4 border-b border-border p-6 sm:flex-row sm:items-center sm:justify-between">
          <div>
            <h2 className="text-lg font-semibold text-foreground">
              Network traffic records
            </h2>

            <p className="mt-1 text-sm text-muted">
              Inspect individual network-flow records returned
              by the FastAPI backend.
            </p>
          </div>

          <div className="relative w-full sm:w-72">
            <Search
              className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-subtle"
              aria-hidden="true"
            />

            <input
              type="search"
              value={searchTerm}
              onChange={(event) =>
                setSearchTerm(event.target.value)
              }
              placeholder="Search traffic records"
              disabled={records.length === 0}
              className="w-full rounded-lg border border-border bg-background py-2.5 pl-10 pr-3 text-sm text-foreground outline-none placeholder:text-subtle disabled:cursor-not-allowed disabled:opacity-60"
            />
          </div>
        </div>

        <div className="overflow-x-auto">
          <table className="min-w-full text-left">
            <thead className="bg-background">
              <tr>
                {TABLE_COLUMNS.map((column) => (
                  <th
                    key={column}
                    scope="col"
                    className="whitespace-nowrap px-5 py-3 text-xs font-semibold uppercase tracking-wide text-subtle"
                  >
                    {column}
                  </th>
                ))}
              </tr>
            </thead>

            <tbody className="divide-y divide-border">
              {filteredRecords.map(
                (record, index) => (
                  <tr
                    key={
                      `${record.timestamp}-${record.src_ip}-${index}`
                    }
                    className="transition hover:bg-surface-hover"
                  >
                    <td className="whitespace-nowrap px-5 py-4 text-sm text-muted">
                      {formatTimestamp(record.timestamp)}
                    </td>

                    <td className="whitespace-nowrap px-5 py-4 font-mono text-sm text-foreground">
                      {record.src_ip}
                    </td>

                    <td className="whitespace-nowrap px-5 py-4 font-mono text-sm text-foreground">
                      {record.dst_ip}
                    </td>

                    <td className="px-5 py-4 text-sm text-muted">
                      {record.src_port}
                    </td>

                    <td className="px-5 py-4 text-sm text-muted">
                      {record.dst_port}
                    </td>

                    <td className="px-5 py-4">
                      <span className="rounded-full bg-primary/10 px-2.5 py-1 text-xs font-semibold text-primary">
                        {record.protocol}
                      </span>
                    </td>

                    <td className="px-5 py-4 text-sm text-muted">
                      {record.pkt_count.toLocaleString()}
                    </td>

                    <td className="px-5 py-4 text-sm text-muted">
                      {record.bytes.toLocaleString()}
                    </td>

                    <td className="px-5 py-4 text-sm text-muted">
                      {record.duration.toFixed(2)}s
                    </td>
                  </tr>
                ),
              )}
            </tbody>
          </table>
        </div>

        {filteredRecords.length === 0 && (
          <div className="flex min-h-52 flex-col items-center justify-center border-t border-border p-8 text-center">
            <Database
              className="h-10 w-10 text-subtle"
              aria-hidden="true"
            />

            <p className="mt-4 font-medium text-foreground">
              {records.length > 0
                ? "No matching records"
                : "No traffic records"}
            </p>

            <p className="mt-2 max-w-md text-sm text-muted">
              {records.length > 0
                ? "Try searching with a different value."
                : (
                  "Choose a CSV file and run the analysis "
                  + "to display its network records."
                )}
            </p>
          </div>
        )}

        {records.length > 0 && (
          <div className="border-t border-border px-6 py-3 text-xs text-subtle">
            Showing {filteredRecords.length} of{" "}
            {records.length} records
          </div>
        )}
      </section>
    </main>
  );
}