import {
  useState,
  type ChangeEvent,
} from "react";
import {
  Activity,
  ChartNoAxesCombined,
  CircleAlert,
  Database,
  LoaderCircle,
  Search,
  ShieldAlert,
  ShieldCheck,
  Upload,
} from "lucide-react";

import { analyzeTrafficFile } from "../service/trafficApi";
import type {
  TrafficSummaryResponse,
} from "../types/traffic.types";


const SUMMARY_CARDS = [
  {
    label: "Total records",
    value: "—",
    description: "No dataset analyzed",
    icon: Database,
    iconStyle: "bg-primary/10 text-primary",
  },
  {
    label: "Normal traffic",
    value: "—",
    description: "Awaiting ML analysis",
    icon: ShieldCheck,
    iconStyle: "bg-low/10 text-low",
  },
  {
    label: "Anomalous traffic",
    value: "—",
    description: "Awaiting ML analysis",
    icon: ShieldAlert,
    iconStyle: "bg-critical/10 text-critical",
  },
  {
    label: "Anomaly rate",
    value: "—",
    description: "Awaiting ML analysis",
    icon: Activity,
    iconStyle: "bg-medium/10 text-medium",
  },
];


const TABLE_COLUMNS = [
  "Timestamp",
  "Source IP",
  "Destination IP",
  "Protocol",
  "Packets",
  "Bytes",
  "Anomaly score",
  "Status",
];


export function TrafficAnalysisPage() {
  const [selectedFile, setSelectedFile] =
    useState<File | null>(null);

  const [analysisResult, setAnalysisResult] =
    useState<TrafficSummaryResponse | null>(null);

  const [isAnalyzing, setIsAnalyzing] =
    useState(false);

  const [errorMessage, setErrorMessage] =
    useState<string | null>(null);


  function handleFileChange(
    event: ChangeEvent<HTMLInputElement>,
  ) {
    const file =
      event.target.files?.[0] ?? null;

    setSelectedFile(file);

    // Remove the previous result when a new file is chosen.
    setAnalysisResult(null);
    setErrorMessage(null);
  }


  async function handleAnalyze() {
    if (!selectedFile) {
      setErrorMessage(
        "Please choose a CSV file before starting the analysis.",
      );

      return;
    }

    setIsAnalyzing(true);
    setErrorMessage(null);
    setAnalysisResult(null);

    try {
      const result =
        await analyzeTrafficFile(selectedFile);

      setAnalysisResult(result);
    } catch (error) {
      const message =
        error instanceof Error
          ? error.message
          : "The traffic dataset could not be analyzed.";

      setErrorMessage(message);
    } finally {
      setIsAnalyzing(false);
    }
  }


  return (
    <main className="space-y-6">
      <header>
        <p className="text-sm font-medium text-primary">
          Network monitoring
        </p>

        <h1 className="mt-1 text-3xl font-bold text-foreground">
          Traffic Analysis
        </h1>

        <p className="mt-2 max-w-3xl text-muted">
          Upload a network-flow dataset and inspect the traffic
          statistics generated by the NetSentry backend.
        </p>
      </header>

      <section className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        {SUMMARY_CARDS.map(
          ({
            label,
            value,
            description,
            icon: Icon,
            iconStyle,
          }) => (
            <article
              key={label}
              className="rounded-2xl border border-border bg-surface p-5"
            >
              <div className="flex items-start justify-between gap-4">
                <div>
                  <p className="text-sm text-muted">
                    {label}
                  </p>

                  <p className="mt-3 text-3xl font-bold text-foreground">
                    {value}
                  </p>

                  <p className="mt-2 text-xs text-subtle">
                    {description}
                  </p>
                </div>

                <div
                  className={`flex h-10 w-10 shrink-0 items-center justify-center rounded-xl ${iconStyle}`}
                >
                  <Icon
                    className="h-5 w-5"
                    aria-hidden="true"
                  />
                </div>
              </div>
            </article>
          ),
        )}
      </section>

      <section className="rounded-2xl border border-primary/30 bg-primary/5 p-6">
        <div className="flex flex-col gap-5">
          <div className="flex flex-col gap-5 sm:flex-row sm:items-center sm:justify-between">
            <div className="flex items-start gap-4">
              <div className="flex h-11 w-11 shrink-0 items-center justify-center rounded-xl bg-primary/10 text-primary">
                <ChartNoAxesCombined
                  className="h-6 w-6"
                  aria-hidden="true"
                />
              </div>

              <div>
                <h2 className="font-semibold text-foreground">
                  {analysisResult
                    ? "Analysis completed"
                    : selectedFile
                      ? "Dataset selected"
                      : "No analysis results yet"}
                </h2>

                <p className="mt-1 max-w-2xl text-sm leading-6 text-muted">
                  {analysisResult
                    ? (
                      `${analysisResult.filename} was successfully `
                      + "analyzed by the FastAPI backend."
                    )
                    : selectedFile
                      ? (
                        `${selectedFile.name} is ready to be `
                        + "sent to the analysis service."
                      )
                      : (
                        "Choose a network-traffic CSV file to "
                        + "generate a real summary using the "
                        + "FastAPI backend."
                      )}
                </p>

                {selectedFile && (
                  <div className="mt-3 flex flex-wrap gap-3 text-xs text-subtle">
                    <span>
                      File: {selectedFile.name}
                    </span>

                    <span>
                      Size:{" "}
                      {(
                        selectedFile.size
                        / 1024
                      ).toFixed(2)}{" "}
                      KB
                    </span>
                  </div>
                )}
              </div>
            </div>

            <div className="flex flex-col gap-3 sm:flex-row">
              <label className="inline-flex shrink-0 cursor-pointer items-center justify-center gap-2 rounded-lg border border-border-strong bg-surface px-4 py-2.5 text-sm font-medium text-foreground transition hover:bg-surface-hover">
                <Upload
                  className="h-4 w-4"
                  aria-hidden="true"
                />

                {selectedFile
                  ? "Change CSV"
                  : "Choose CSV"}

                <input
                  type="file"
                  accept=".csv,text/csv"
                  onChange={handleFileChange}
                  className="sr-only"
                />
              </label>

              <button
                type="button"
                onClick={() => void handleAnalyze()}
                disabled={!selectedFile || isAnalyzing}
                className="inline-flex shrink-0 items-center justify-center gap-2 rounded-lg bg-primary px-4 py-2.5 text-sm font-medium text-primary-foreground transition hover:opacity-90 disabled:cursor-not-allowed disabled:opacity-50"
              >
                {isAnalyzing ? (
                  <>
                    <LoaderCircle
                      className="h-4 w-4 animate-spin"
                      aria-hidden="true"
                    />

                    Analyzing...
                  </>
                ) : (
                  <>
                    <ChartNoAxesCombined
                      className="h-4 w-4"
                      aria-hidden="true"
                    />

                    Analyze dataset
                  </>
                )}
              </button>
            </div>
          </div>

          {errorMessage && (
            <div
              role="alert"
              className="flex items-start gap-3 rounded-xl border border-critical/30 bg-critical/10 p-4 text-sm text-critical"
            >
              <CircleAlert
                className="mt-0.5 h-5 w-5 shrink-0"
                aria-hidden="true"
              />

              <p>{errorMessage}</p>
            </div>
          )}

          {analysisResult && (
            <div className="rounded-xl border border-low/30 bg-low/10 p-4 text-sm text-low">
              The backend successfully analyzed{" "}
              {analysisResult.total_connections.toLocaleString()}{" "}
              network connections.
            </div>
          )}
        </div>
      </section>

      <section className="grid gap-6 xl:grid-cols-2">
        <article className="rounded-2xl border border-border bg-surface p-6">
          <div>
            <h2 className="text-lg font-semibold text-foreground">
              Traffic classification
            </h2>

            <p className="mt-1 text-sm text-muted">
              Normal and anomalous network-flow distribution.
            </p>
          </div>

          <div className="mt-6 flex min-h-64 flex-col items-center justify-center rounded-xl border border-dashed border-border-strong bg-background p-8 text-center">
            <ChartNoAxesCombined
              className="h-10 w-10 text-subtle"
              aria-hidden="true"
            />

            <p className="mt-4 font-medium text-foreground">
              Classification chart unavailable
            </p>

            <p className="mt-2 max-w-sm text-sm text-muted">
              This chart will become available after the
              anomaly-detection model is implemented.
            </p>
          </div>
        </article>

        <article className="rounded-2xl border border-border bg-surface p-6">
          <div>
            <h2 className="text-lg font-semibold text-foreground">
              Protocol distribution
            </h2>

            <p className="mt-1 text-sm text-muted">
              Distribution of traffic across network protocols.
            </p>
          </div>

          <div className="mt-6 flex min-h-64 flex-col items-center justify-center rounded-xl border border-dashed border-border-strong bg-background p-8 text-center">
            <Activity
              className="h-10 w-10 text-subtle"
              aria-hidden="true"
            />

            <p className="mt-4 font-medium text-foreground">
              Protocol data unavailable
            </p>

            <p className="mt-2 max-w-sm text-sm text-muted">
              Protocol statistics will appear after the selected
              dataset has been analyzed.
            </p>
          </div>
        </article>
      </section>

      <section className="overflow-hidden rounded-2xl border border-border bg-surface">
        <div className="flex flex-col gap-4 border-b border-border p-6 sm:flex-row sm:items-center sm:justify-between">
          <div>
            <h2 className="text-lg font-semibold text-foreground">
              Network traffic records
            </h2>

            <p className="mt-1 text-sm text-muted">
              Inspect individual network-flow records and their
              analysis status.
            </p>
          </div>

          <div className="relative w-full sm:w-72">
            <Search
              className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-subtle"
              aria-hidden="true"
            />

            <input
              type="search"
              placeholder="Search traffic records"
              disabled
              className="w-full rounded-lg border border-border bg-background py-2.5 pl-10 pr-3 text-sm text-foreground outline-none placeholder:text-subtle disabled:cursor-not-allowed disabled:opacity-60"
            />
          </div>
        </div>

        <div className="overflow-x-auto">
          <table className="min-w-full text-left">
            <thead className="bg-background">
              <tr>
                {TABLE_COLUMNS.map((column) => (
                  <th
                    key={column}
                    scope="col"
                    className="whitespace-nowrap px-5 py-3 text-xs font-semibold uppercase tracking-wide text-subtle"
                  >
                    {column}
                  </th>
                ))}
              </tr>
            </thead>
          </table>
        </div>

        <div className="flex min-h-52 flex-col items-center justify-center border-t border-border p-8 text-center">
          <Database
            className="h-10 w-10 text-subtle"
            aria-hidden="true"
          />

          <p className="mt-4 font-medium text-foreground">
            No traffic records
          </p>

          <p className="mt-2 max-w-md text-sm text-muted">
            Individual records will appear after the backend
            provides record-level traffic results.
          </p>
        </div>
      </section>
    </main>
  );
}